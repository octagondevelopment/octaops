param(
  [Parameter(Mandatory)][string]$Csv,
  [string]$Out = "$PSScriptRoot\..\supabase\seed\parts.sql"
)

function Q($v) { if ([string]::IsNullOrWhiteSpace($v)) { 'null' } else { "'" + $v.Replace("'", "''") + "'" } }
function N($v) { if ([string]::IsNullOrWhiteSpace($v)) { 'null' } else { $v } }

$rows = Import-Csv -Encoding UTF8 $Csv
$sql = New-Object System.Collections.Generic.List[string]
$sql.Add('-- Generated by scripts/build-parts-seed.ps1 from the catalog CSV. Safe to re-run (upsert on sku).')
$sql.Add('insert into parts (sku, sku_8digit, page, name_en, name_es, module, subassembly, price_cad, qty_per_machine, on_hand, notes) values')

$values = foreach ($r in $rows) {
  '(' + (@(
    (Q $r.sku), (Q $r.sku_8digit), (N $r.page), (Q $r.name_en), (Q $r.name_es),
    (Q $r.module), (Q $r.subassembly), (N $r.price_cad), (N $r.qty_per_machine), (N $r.on_hand), (Q $r.notes)
  ) -join ', ') + ')'
}
$sql.Add(($values -join ",`n"))
$sql.Add('on conflict (sku) do update set')
$sql.Add('  sku_8digit = excluded.sku_8digit, page = excluded.page, name_en = excluded.name_en, name_es = excluded.name_es,')
$sql.Add('  module = excluded.module, subassembly = excluded.subassembly, price_cad = excluded.price_cad,')
$sql.Add('  qty_per_machine = excluded.qty_per_machine, on_hand = excluded.on_hand, notes = excluded.notes;')

New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
[System.IO.File]::WriteAllText($Out, ($sql -join "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
"Wrote $($rows.Count) parts to $Out"
